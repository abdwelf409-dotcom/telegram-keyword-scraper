def is_ad(text):
    """فلتر متطور وحساس لمنع الإعلانات التعليمية والتجارية"""
    if not text:
        return False
    text_lower = text.lower()
    
    # 1. مطابقة أي نمط إعلاني ترويجي للمكاتب أو المعاهد
    for pattern in AD_PATTERNS:
        if re.search(pattern, text_lower):
            return True
            
    # 2. فحص الرسائل الطويلة (إعلانات المكاتب غالباً تتجاوز 150 حرف وتحتوي كلمات خدمات متعددة)
    if len(text) > 150:
        ad_keywords_count = sum(1 for word in ['لخدمات', 'فريق', 'دكتور', 'رسائل', 'الماجستير', 'الدكتوراه', 'تحليل', 'تنسيق', 'ترجمه', 'توفير', 'المراجع', 'التواصل', 'خصم', 'اكاديمية', 'معلمين'] if word in text_lower)
        if ad_keywords_count >= 2:
            return True
            
    return False

def get_category(keyword):
    kw_lower = keyword.lower()
    for cat, words in CATEGORIES.items():
        if cat == 'عام':
            continue
        for w in words:
            if w.lower() in kw_lower:
                return cat
    return 'عام'

def fuzzy_similarity(s1, s2):
    """
    حساب درجة التشابه بين سلسلتين نصيتين باستخدام المسافة بينهما.
    ترجع قيمة بين 0 و 1 (1 = تطابق تام).
    متسامحة مع أخطاء: حروف زايدة، ناقصة، أو مبدلة.
    """
    s1, s2 = s1.lower(), s2.lower()
    if len(s1) < 4 or len(s2) < 4:
        return 1.0 if s1 == s2 else 0.0
    
    # مسافة ليفينشتاين (تحتاج مسافات أقل = تطابق أكثر)
    m, n = len(s1), len(s2)
    dp = [[0] * (n + 1) for _ in range(m + 1)]
    
    for i in range(m + 1):
        dp[i][0] = i
    for j in range(n + 1):
        dp[0][j] = j
    
    for i in range(1, m + 1):
        for j in range(1, n + 1):
            cost = 0 if s1[i-1] == s2[j-1] else 1
            dp[i][j] = min(dp[i-1][j] + 1, dp[i][j-1] + 1, dp[i-1][j-1] + cost)
    
    max_len = max(len(s1), len(s2))
    similarity = 1.0 - (dp[m][n] / max_len)
    return similarity

def check_keywords_fast(text):
    """بحث ذكي يتحمل الأخطاء الإملائية والكلمات المتشابهة"""
    if not text:
        return None
    
    text_lower = text.lower()
    
    # 1. أولاً: مطابقة مباشرة سريعة (O(1) للكلمات المطابقة تماماً)
    for kw in KEYWORDS_SET:
        if kw.lower() in text_lower:
            return kw
    
    # 2. ثانياً: مطابقة ذكية للكلمات التي تحتمل أخطاء إملائية
    # تقسيم النص لكلمات للبحث الجزئي
    text_words = re.split(r'\s+', text_lower)
    
    for kw in KEYWORDS_SET:
        kw_lower = kw.lower()
        kw_words = kw_lower.split()
        
        # إذا كانت الكلمة المفتاحية قصيرة، نبحث عن تطابق عالي
        if len(kw_lower) <= 10:
            # فحص مباشر لأي جزء من النص
            for i in range(len(text_lower) - len(kw_lower) + 1):
                window = text_lower[i:i+len(kw_lower)]
                if fuzzy_similarity(window, kw_lower) >= 0.85:
                    return kw
        else:
            # للكلمات الطويلة: البحث عن الكلمات المفتاحية في أي ترتيب
            if len(kw_words) >= 2:
                found_count = 0
                for kw_word in kw_words:
                    if len(kw_word) <= 3:
                        # كلمات صغيرة جداً تحتاج تطابق مباشر
                        if kw_word in text_words:
                            found_count += 1
                    else:
                        # كلمات متوسطة/طويلة نفحصها بالتشابه
                        for tw in text_words:
                            if len(tw) >= len(kw_word) - 1:
                                # فحص نافذة متحركة داخل الكلمة
                                for i in range(max(1, len(tw) - len(kw_word) + 1)):
                                    window = tw[i:i+len(kw_word)]
                                    if fuzzy_similarity(window, kw_word) >= 0.8:
                                        found_count += 1
                                        break
                # إذا تطابقت 70% من كلمات العبارة المفتاحية
                if found_count >= len(kw_words) * 0.7:
                    return kw
            else:
                # كلمة واحدة طويلة: نبحث عنها بتشابه في النص الكامل
                for tw in text_words:
                    if fuzzy_similarity(tw, kw_lower) >= 0.85:
                        return kw
                    # فحص جزئي
                    for i in range(max(1, len(tw) - len(kw_lower) + 1)):
                        window = tw[i:i+len(kw_lower)]
                        if fuzzy_similarity(window, kw_lower) >= 0.85:
                            return kw
    
    return None

async def get_group_link(chat):
    try:
        if hasattr(chat, 'username') and chat.username:
            return "https://t.me/" + str(chat.username)
    except:
        pass
    return None

# ========== الحدث الرئيسي للبوت ==========
async def main():
    print("🚀 البوت يعمل والفلتر الحساس للإعلانات نشط...")
    await client.start()
    print("✅ تم تسجيل الدخول بنجاح!")

    @client.on(events.NewMessage)
    async def handler(event):
        chat = await event.get_chat()
        
        if hasattr(chat, 'id') and chat.id == TARGET_CHANNEL:
            return
        
        if not event.is_group:
            return
        
        text = event.raw_text or ""
        if not text:
            return
        
        # حظر واستبعاد أي إعلان أو رسالة مكتبية كبيرة فوراً
        if is_ad(text):
            return
        
        # البحث عن الكلمات المفتاحية للطلاب حصراً
        keyword = check_keywords_fast(text)
        
        if keyword:
            sender = await event.get_sender()
            group_name = getattr(chat, 'title', 'مجموعة غير معروفة')
            group_link = await get_group_link(chat)
            
            first = getattr(sender, 'first_name', '') or ''
            last = getattr(sender, 'last_name', '') or ''
            full_name = (first + ' ' + last).strip() or 'مجهول'
            username = sender.username
            user_id = sender.id
            
            user_display = "[" + full_name + "](tg://user?id=" + str(user_id) + ")"
            
            if group_link:
                group_display = "[" + group_name + "](" + group_link + ")"
            else:
                group_display = group_name
            
            category = get_category(keyword)
            color = CATEGORY_COLORS.get(category, '📌')
            
            if len(text) > 400:
                short_text = text[:400] + "\n... (تم اختصار الرسالة)"
            else:
                short_text = text
            
            msg = ""
            msg += color + " **طلب جديد - " + category + "**\n\n"
            msg += "📌 **الكلمة المفتاحية:** `" + keyword + "`\n"
            msg += "📂 **التصنيف:** " + category + "\n\n"
            msg += "👤 **المرسل:** " + user_display + "\n"
            
            if username:
                msg += "🔹 **اليوزر:** @" + username + "\n"
            else:
                msg += "🔹 **اليوزر:** لا يوجد\n"
                
            msg += "🆔 **الايدي:** `" + str(user_id) + "`\n\n"
            msg += "💬 **المجموعة:** " + group_display + "\n\n"
            msg += "📝 **الرسالة:**\n```\n"
            msg += short_text
            msg += "\n```\n\n"
            msg += "⏰ **الوقت:** " + str(event.date.strftime('%Y-%m-%d %H:%M:%S'))
            
            try:
                await client.send_message(TARGET_CHANNEL, msg, link_preview=False)
                print("✅ [طلب طالب حقيقي] " + full_name + " | " + keyword)
            except Exception as e:
                print("❌ خطأ: " + str(e))

    await client.run_until_disconnected()

