client = TelegramClient(StringSession(SESSION_STRING), API_ID, API_HASH)

def is_ad(text):
    """فحص إذا كانت الرسالة إعلان"""
    if not text:
        return False
    text_lower = text.lower()
    for pattern in AD_PATTERNS:
        if re.search(pattern, text_lower):
            return True
    # إذا الرسالة أطول من 800 حرف وفيها كلمات إعلانية
    if len(text) > 800:
        ad_words = ['عرض', 'سعر', 'خصم', 'للبيع', 'اشتري', 'متجر', 'توصيل']
        count = sum(1 for w in ad_words if w in text_lower)
        if count >= 3:
            return True
    return False

def get_category(keyword):
    kw_lower = keyword.lower()
    for cat, words in CATEGORIES.items():
        if cat == 'عام':
            continue
        for w in words:
            if w.lower() in kw_lower:
                return cat
    return 'عام'

def check_keywords_fast(text):
    """بحث فوري - O(1)"""
    if not text:
        return None
    text_lower = text.lower()
    for kw in KEYWORDS_SET:
        if kw.lower() in text_lower:
            return kw
    return None

async def get_group_link(chat):
    try:
        if hasattr(chat, 'username') and chat.username:
            return "https://t.me/" + str(chat.username)
    except:
        pass
    return None

# ========== البوت ==========
async def main():
    print("🚀 البوت بدأ العمل...")
    await client.start()
    print("✅ تم تسجيل الدخول!")

    @client.on(events.NewMessage)
    async def handler(event):
        chat = await event.get_chat()
        
        if hasattr(chat, 'id') and chat.id == TARGET_CHANNEL:
            return
        
        if not event.is_group:
            return
        
        text = event.raw_text or ""
        if not text:
            return
        
        # فلتر الإعلانات
        if is_ad(text):
            print("🚫 إعلان متجاهل: " + text[:50] + "...")
            return
        
        # البحث الفوري
        keyword = check_keywords_fast(text)
        
        if keyword:
            sender = await event.get_sender()
            group_name = getattr(chat, 'title', 'مجموعة غير معروفة')
            group_link = await get_group_link(chat)
            
            first = getattr(sender, 'first_name', '') or ''
            last = getattr(sender, 'last_name', '') or ''
            full_name = (first + ' ' + last).strip() or 'مجهول'
            username = sender.username
            user_id = sender.id
            
            # رابط المستخدم
            user_display = "[" + full_name + "](tg://user?id=" + str(user_id) + ")"
            
            # رابط المجموعة
            if group_link:
                group_display = "[" + group_name + "](" + group_link + ")"
            else:
                group_display = group_name
            
            category = get_category(keyword)
            color = CATEGORY_COLORS.get(category, '📌')
            
            # اختصار الرسالة الطويلة
            if len(text) > 400:
                short_text = text[:400] + "\n... (تم اختصار الرسالة)"
            else:
                short_text = text
            
            # بناء الرسالة
            msg = ""
            msg += color + " **طلب جديد - " + category + "**\n\n"
            msg += "📌 **الكلمة المفتاحية:** `" + keyword + "`\n"
            msg += "📂 **التصنيف:** " + category + "\n\n"
            msg += "👤 **المرسل:** " + user_display + "\n"
            
            if username:
                msg += "🔹 **اليوزر:** @" + username + "\n"
            else:
                msg += "🔹 **اليوزر:** لا يوجد\n"
                
            msg += "🆔 **الايدي:** `" + str(user_id) + "`\n\n"
            msg += "💬 **المجموعة:** " + group_display + "\n\n"
            msg += "📝 **الرسالة:**\n```\n"
            msg += short_text
            msg += "\n```\n\n"
            msg += "⏰ **الوقت:** " + str(event.date.strftime('%Y-%m-%d %H:%M:%S'))
            
            try:
                await client.send_message(TARGET_CHANNEL, msg, link_preview=False)
                print("✅ [" + category + "] " + full_name + " | " + keyword + " | " + str(len(text)) + " حرف")
            except Exception as e:
                print("❌ خطأ: " + str(e))

    await client.run_until_disconnected()

